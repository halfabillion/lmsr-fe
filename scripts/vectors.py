#!/usr/bin/env python3
"""Generate exact N-outcome LMSR reference vectors for lmsr-fe.

Uses Python's decimal module at 80 significant digits, then floors to wei
(1e-18). Writes src/vectors.fe, a Fe test module (hand-picked CASES plus
PROP_CASES seeded-random property vectors), and src/prop_market_tests.fe
(seeded-random trade sequences against the Market contract). Re-run with:

    python3 scripts/vectors.py && fe fmt && fe test
"""
from decimal import Decimal, getcontext, ROUND_FLOOR
from pathlib import Path
import random

getcontext().prec = 80
WAD = Decimal(10) ** 18


def cost(q, b):
    m = max(q)
    return m + b * sum(((x - m) / b).exp() for x in q).ln()


def price(q, b, i):
    m = max(q)
    terms = [((x - m) / b).exp() for x in q]
    return terms[i] / sum(terms)


def wei(x):
    return int((x * WAD).to_integral_value(rounding=ROUND_FLOOR))


def fe_u(x):
    return f"{x:_}"


# (name, capacity N, live quantities q (in whole tokens), b, trade outcome, trade amount)
CASES = [
    ("n3_flat", 3, [0, 0, 0], 100, 0, 10),
    ("n3_skewed", 3, [120, 15, 0], 100, 2, 40),
    ("n4_flat", 4, [0, 0, 0, 0], 50, 3, 5),
    ("n4_skewed", 4, [300, 280, 10, 0], 100, 1, 25),
    ("n4_large_gap", 4, [5000, 0, 0, 0], 100, 1, 100),
    ("n5_of_8", 8, [7, 3, 0, 42, 11], 25, 3, 9),
]


def arr(q, cap):
    full = [wei(Decimal(x)) for x in q] + [0] * (cap - len(q))
    return "[" + ", ".join(fe_u(v) for v in full) + "]"


def main():
    out = [
        "// GENERATED by scripts/vectors.py -- do not edit by hand.",
        "// Reference values: Python decimal, 80 significant digits, floored to wei.",
        "",
        "use ingot::{WAD, cost_err_n, lmsr_cost_n, lmsr_price_n, lmsr_buy_cost_n, lmsr_sell_payout_n}",
        "",
        "fn near(_ got: u256, _ want: u256, _ tol: u256) -> bool {",
        "    if got >= want {",
        "        return got - want <= tol",
        "    }",
        "    want - got <= tol",
        "}",
    ]
    for name, cap, q, b, i, amt in CASES:
        n = len(q)
        qd = [Decimal(x) for x in q]
        bd = Decimal(b)
        c0 = cost(qd, bd)
        up = list(qd); up[i] += amt
        buy_exact = wei(cost(up, bd) - c0)
        prices = [wei(price(qd, bd, k)) for k in range(n)]
        out += [
            "",
            "#[test]",
            f"fn vec_{name}() {{",
            f"    let q: [u256; {cap}] = {arr(q, cap)}",
            f"    let n: usize = {n}",
            f"    let b: u256 = {b} * WAD",
            "    let tol: u256 = cost_err_n(b, n)",
            f"    assert!(near(lmsr_cost_n(q, n, b), {fe_u(wei(c0))}, tol))",
        ]
        for k, p in enumerate(prices):
            out.append(f"    assert!(near(lmsr_price_n(q, n, b, {k}), {fe_u(p)}, 16))")
        out += [
            "    // Prices are rounded down: they sum to at most 1.0, within 16*n wei.",
            "    var sum: u256 = 0",
            "    var k: usize = 0",
            "    while k < n {",
            "        sum += lmsr_price_n(q, n, b, k)",
            "        k += 1",
            "    }",
            "    assert!(sum <= WAD && WAD - sum <= 16 * (n as u256))",
            f"    // Buy {amt} of outcome {i}: never under-charges the exact cost.",
            f"    let paid: u256 = lmsr_buy_cost_n(q, n, b, {i}, {amt} * WAD)",
            f"    assert!(paid > {fe_u(buy_exact)})",
            f"    assert!(paid - {fe_u(buy_exact)} <= 2 * tol)",
            f"    // Sell it straight back: never over-pays, round trip loses money.",
            "    var after = q",
            f"    after[{i}] = q[{i}] + {amt} * WAD",
            f"    let back: u256 = lmsr_sell_payout_n(after, n, b, {i}, {amt} * WAD)",
            f"    assert!(back <= {fe_u(buy_exact)})",
            "    assert!(back < paid)",
            "}",
        ]
    out += prop_vectors()
    src = Path(__file__).resolve().parent.parent.joinpath("src")
    src.joinpath("vectors.fe").write_text("\n".join(out) + "\n")
    src.joinpath("prop_market_tests.fe").write_text("\n".join(prop_market()) + "\n")


# ---------------------------------------------------------------------------
# M3 property-style vectors: seeded-random books, liquidity and trade sizes
# (all in raw wei, so fractional quantities are covered). For each case the
# contract-facing library functions must round in the maker's favour against
# the 80-digit exact LMSR: buy cost >= exact, sell payout <= exact, and both
# within the documented error budget.
# ---------------------------------------------------------------------------

SEED = 20261116
PROP_CASES = 40
W = 10**18  # integer WAD for the random generators


def dec(w):
    return Decimal(w) / WAD


def prop_vectors():
    rng = random.Random(SEED)
    out = []
    for c in range(PROP_CASES):
        n = rng.randint(2, 8)
        b = rng.randint(1, 500) * W + rng.randint(0, W - 1)
        # Mostly books within a few b of each other, sometimes one far ahead.
        spread = b * rng.choice([1, 3, 8, 40])
        q = [rng.randint(0, spread) for _ in range(n)]
        i = rng.randrange(n)
        buy_amt = rng.randint(1, 3 * b)
        sell_amt = rng.randint(0, q[i]) if q[i] > 0 else 0
        qd = [dec(x) for x in q]
        bd = dec(b)
        c0 = cost(qd, bd)
        up = list(qd); up[i] += dec(buy_amt)
        buy_exact = wei(cost(up, bd) - c0)
        down = list(qd); down[i] -= dec(sell_amt)
        sell_exact = wei(c0 - cost(down, bd))
        out += [
            "",
            "#[test]",
            f"fn prop_{c:02d}_n{n}() {{",
            f"    let q: [u256; 8] = {arr_wei(q, 8)}",
            f"    let n: usize = {n}",
            f"    let b: u256 = {fe_u(b)}",
            "    let tol: u256 = cost_err_n(b, n)",
            f"    let paid: u256 = lmsr_buy_cost_n(q, n, b, {i}, {fe_u(buy_amt)})",
            f"    assert!(paid >= {fe_u(buy_exact)}, \"buy under exact\")",
            f"    assert!(paid - {fe_u(buy_exact)} <= 2 * tol + 1, \"buy over budget\")",
        ]
        if sell_amt > 0:
            out += [
                f"    let back: u256 = lmsr_sell_payout_n(q, n, b, {i}, {fe_u(sell_amt)})",
                f"    assert!(back <= {fe_u(sell_exact)}, \"sell over exact\")",
                f"    assert!({fe_u(sell_exact)} - back <= 2 * tol + 1, \"sell under budget\")",
            ]
        out.append("}")
    return out


def arr_wei(q, cap):
    full = list(q) + [0] * (cap - len(q))
    return "[" + ", ".join(fe_u(v) for v in full) + "]"


# Seeded-random trade sequences against the deployed Market. After every step
# the contract balance must cover the largest outstanding outcome (the payout
# if that outcome wins), i.e. the maker is solvent whatever the resolution.
SEQUENCES = [("n3", 3, 30, 1), ("n5", 5, 30, 2), ("n8", 8, 30, 3)]


def prop_market():
    rng = random.Random(SEED + 1)
    out = [
        "// GENERATED by scripts/vectors.py -- do not edit by hand.",
        "// Seeded-random trade sequences: after each step the Market's balance",
        "// must be >= the largest outstanding share count (solvency for any winner).",
        "",
        "use ingot::market::{Market, MarketMsg}",
        "use ingot::{WAD, lmsr_max_loss}",
        "use std::evm::{ether, wei}",
        "",
        "const B: u256 = 10_000_000_000_000_000_000",
        "const FAR: u256 = 4_000_000_000",
        "",
        "fn solvent(_ m: Address, _ n: u256) -> bool uses (evm: mut Evm) {",
        "    var worst: u256 = 0",
        "    var k: u256 = 0",
        "    while k < n {",
        "        let o: u256 = evm.call(addr: m, gas: 3000000, value: Wei::zero(), message: MarketMsg::Outstanding { outcome: k })",
        "        if o > worst { worst = o }",
        "        k += 1",
        "    }",
        "    evm.balance(m) >= wei(worst)",
        "}",
        "",
        "fn buy(_ m: Address, _ outcome: u256, _ amount: u256) uses (evm: mut Evm) {",
        "    let _: u256 = evm.call(addr: m, gas: 3000000, value: ether(1000), message: MarketMsg::Buy { outcome, amount, refund_to: Address::new(0xbeef) })",
        "}",
        "",
        "fn sell(_ m: Address, _ outcome: u256, _ amount: u256) uses (evm: mut Evm) {",
        "    let _: u256 = evm.call(addr: m, gas: 3000000, value: Wei::zero(), message: MarketMsg::Sell { outcome, amount, to: Address::new(0xbeef) })",
        "}",
    ]
    b = 10 * 10**18
    for name, n, steps, salt in SEQUENCES:
        held = [0] * n
        out += [
            "",
            "#[test(balance = 1_000_000_000_000_000_000_000_000)]",
            f"fn prop_seq_{name}() uses (evm: mut Evm) {{",
            f"    let m = evm.create2<Market>(value: wei(lmsr_max_loss(B, {n})), args: (B, {n}, FAR), salt: {salt})",
            f"    assert!(solvent(m, {n}))",
        ]
        for _ in range(steps):
            k = rng.randrange(n)
            if held[k] > 0 and rng.random() < 0.4:
                amt = rng.randint(1, held[k])
                held[k] -= amt
                out.append(f"    sell(m, {k}, {fe_u(amt)})")
            else:
                amt = rng.randint(1, 4 * b)
                held[k] += amt
                out.append(f"    buy(m, {k}, {fe_u(amt)})")
            out.append(f"    assert!(solvent(m, {n}))")
        out.append("}")
    return out


if __name__ == "__main__":
    main()
